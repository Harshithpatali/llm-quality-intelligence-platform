"""Offline validation of automated rubric decisions against human labels.

Input is JSONL with one record per independently reviewed response:
  {"judge_decision":"pass|review|fail",
   "human_decision":"accept|revise|reject|escalate",
   "category":"optional"}
No synthetic or inferred labels are generated by this module.
"""
from __future__ import annotations

import argparse
import json
import random
from collections import Counter
from pathlib import Path
from typing import Iterable

DECISIONS = ("pass", "review", "fail")
HUMAN_MAP = {
    "accept": "pass",
    "revise": "review",
    "reject": "fail",
    "escalate": "fail",
    "pass": "pass",
    "review": "review",
    "fail": "fail",
}


def _canonical(value: object, *, human: bool) -> str:
    mapping = HUMAN_MAP if human else {x: x for x in DECISIONS}
    key = str(value or "").strip().casefold()
    if key not in mapping:
        raise ValueError(f"Unsupported {'human' if human else 'judge'} decision: {value!r}")
    return mapping[key]


def _kappa(matrix: dict[str, dict[str, int]], n: int) -> float | None:
    if not n:
        return None
    observed = sum(matrix[label][label] for label in DECISIONS) / n
    expected = sum(
        sum(matrix[row][col] for col in DECISIONS)
        * sum(matrix[col][row] for col in DECISIONS)
        for row in DECISIONS
    ) / (n * n)
    if expected == 1:
        return 1.0 if observed == 1 else 0.0
    return (observed - expected) / (1 - expected)


def _metrics(rows: list[tuple[str, str]]) -> dict:
    n = len(rows)
    matrix = {a: {b: 0 for b in DECISIONS} for a in DECISIONS}
    for human, judge in rows:
        matrix[human][judge] += 1

    per_class = {}
    recalls = []
    f1_values = []
    for label in DECISIONS:
        tp = matrix[label][label]
        fp = sum(matrix[other][label] for other in DECISIONS if other != label)
        fn = sum(matrix[label][other] for other in DECISIONS if other != label)
        support = sum(matrix[label].values())
        precision = tp / (tp + fp) if tp + fp else 0.0
        recall = tp / support if support else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        per_class[label] = {
            "support": support,
            "precision": round(precision, 4),
            "recall": round(recall, 4),
            "f1": round(f1, 4),
        }
        if support:
            recalls.append(recall)
            f1_values.append(f1)

    correct = sum(matrix[label][label] for label in DECISIONS)
    return {
        "n": n,
        "labels": list(DECISIONS),
        "confusion_matrix": matrix,
        "accuracy": round(correct / n, 4) if n else None,
        "balanced_accuracy": round(sum(recalls) / len(recalls), 4) if recalls else None,
        "macro_f1_observed_classes": round(sum(f1_values) / len(f1_values), 4) if f1_values else None,
        "cohen_kappa": round(_kappa(matrix, n), 4) if n else None,
        "per_class": per_class,
    }


def validate_judge(
    records: Iterable[dict],
    *,
    bootstrap_iterations: int = 2000,
    seed: int = 42,
) -> dict:
    """Compare judge decisions with human labels and bootstrap accuracy CI."""
    if bootstrap_iterations < 100:
        raise ValueError("bootstrap_iterations must be at least 100")
    pairs = []
    categories: dict[str, list[tuple[str, str]]] = {}
    for index, row in enumerate(records):
        if "judge_decision" not in row or "human_decision" not in row:
            raise ValueError(f"Record {index} must contain judge_decision and human_decision")
        pair = (
            _canonical(row["human_decision"], human=True),
            _canonical(row["judge_decision"], human=False),
        )
        pairs.append(pair)
        category = str(row.get("category") or "uncategorized")
        categories.setdefault(category, []).append(pair)

    result = _metrics(pairs)
    result["method"] = "paired_nonparametric_bootstrap_accuracy_percentile"
    result["bootstrap_iterations"] = bootstrap_iterations
    result["seed"] = seed
    if pairs:
        rng = random.Random(seed)
        n = len(pairs)
        estimates = []
        for _ in range(bootstrap_iterations):
            sample = [pairs[rng.randrange(n)] for _ in range(n)]
            estimates.append(sum(h == j for h, j in sample) / n)
        estimates.sort()
        lo = estimates[int(0.025 * (bootstrap_iterations - 1))]
        hi = estimates[int(0.975 * (bootstrap_iterations - 1))]
        result["accuracy_ci_95"] = [round(lo, 4), round(hi, 4)]
    else:
        result["accuracy_ci_95"] = None

    result["by_category"] = {
        category: _metrics(values) for category, values in sorted(categories.items())
    }
    result["limitations"] = [
        "Human labels are the reference for this analysis, not infallible ground truth.",
        "Escalate is mapped to fail; document this policy when interpreting results.",
        "A small or imbalanced sample can make class metrics and confidence intervals unstable.",
        "Agreement does not establish factual correctness; inspect disagreements and evidence.",
    ]
    return result


def load_jsonl(path: str | Path) -> list[dict]:
    rows = []
    with Path(path).open(encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            if line.strip():
                try:
                    value = json.loads(line)
                except json.JSONDecodeError as exc:
                    raise ValueError(f"Invalid JSON on line {line_number}: {exc}") from exc
                if not isinstance(value, dict):
                    raise ValueError(f"Line {line_number} must contain a JSON object")
                rows.append(value)
    return rows


def main() -> None:
    parser = argparse.ArgumentParser(description="Validate LLM judge decisions against human labels.")
    parser.add_argument("input", help="JSONL file with judge_decision and human_decision fields")
    parser.add_argument("--output", default="judge_validation_report.json")
    parser.add_argument("--bootstrap-iterations", type=int, default=2000)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()
    report = validate_judge(
        load_jsonl(args.input),
        bootstrap_iterations=args.bootstrap_iterations,
        seed=args.seed,
    )
    Path(args.output).write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
