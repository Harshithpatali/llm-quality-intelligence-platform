"""Evaluator calibration and reliability analysis.

Input JSONL: one row per response, with unique trace_id, split (validation|holdout),
reviewer_a_decision, reviewer_b_decision, adjudicated_decision, judge_decision,
judge_score in [0, 1], and optional dimensions mapping dimension names to
{reviewer_a, reviewer_b, judge, adjudicated} labels.

Thresholds are selected only on validation rows, then frozen and evaluated once
on holdout rows. No labels or examples are generated by this module.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Iterable

LABELS = ("fail", "review", "pass")
SPLITS = ("validation", "holdout")


def _label(value: object, field: str) -> str:
    value = str(value or "").strip().casefold()
    aliases = {"accept": "pass", "revise": "review", "reject": "fail", "escalate": "fail"}
    value = aliases.get(value, value)
    if value not in LABELS:
        raise ValueError(f"{field} must be one of {LABELS}; got {value!r}")
    return value


def _matrix(pairs: list[tuple[str, str]]) -> dict:
    return {a: {b: sum(x == a and y == b for x, y in pairs) for b in LABELS} for a in LABELS}


def _kappa(matrix: dict, n: int) -> float | None:
    if not n:
        return None
    observed = sum(matrix[x][x] for x in LABELS) / n
    expected = sum(sum(matrix[a].values()) * sum(matrix[b][a] for b in LABELS)
                   for a in LABELS) / (n * n)
    return (observed - expected) / (1 - expected) if expected < 1 else (1.0 if observed == 1 else 0.0)


def agreement(pairs: list[tuple[str, str]]) -> dict:
    n = len(pairs)
    matrix = _matrix(pairs)
    per_class = {}
    f1s = []
    recalls = []
    for label in LABELS:
        tp = matrix[label][label]
        fp = sum(matrix[row][label] for row in LABELS if row != label)
        fn = sum(matrix[label][col] for col in LABELS if col != label)
        support = sum(matrix[label].values())
        precision = tp / (tp + fp) if tp + fp else 0.0
        recall = tp / support if support else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        per_class[label] = {"support": support, "precision": round(precision, 4),
                            "recall": round(recall, 4), "f1": round(f1, 4)}
        if support:
            f1s.append(f1)
            recalls.append(recall)
    return {
        "n": n,
        "exact_agreement": round(sum(a == b for a, b in pairs) / n, 4) if n else None,
        "accuracy": round(sum(a == b for a, b in pairs) / n, 4) if n else None,
        "cohen_kappa": round(_kappa(matrix, n), 4) if n else None,
        "balanced_accuracy": round(sum(recalls) / len(recalls), 4) if recalls else None,
        "macro_f1_observed_classes": round(sum(f1s) / len(f1s), 4) if f1s else None,
        "confusion_matrix": matrix, "per_class": per_class,
    }


def _predict(score: float, fail_below: float, pass_at_or_above: float) -> str:
    if score < fail_below:
        return "fail"
    if score >= pass_at_or_above:
        return "pass"
    return "review"


def _macro_f1(truth: list[str], predicted: list[str]) -> float:
    result = agreement(list(zip(truth, predicted)))
    return result["macro_f1_observed_classes"] or 0.0


def calibrate_thresholds(rows: list[dict]) -> dict:
    """Select two cutoffs on validation only, maximizing macro-F1."""
    if len(rows) < 12:
        raise ValueError("At least 12 validation rows are required for threshold calibration")
    scores = [float(r["judge_score"]) for r in rows]
    if any(not 0 <= x <= 1 for x in scores):
        raise ValueError("judge_score must be between 0 and 1")
    truth = [_label(r["adjudicated_decision"], "adjudicated_decision") for r in rows]
    candidates = sorted(set([0.0, 1.0] + scores))
    best = None
    for low in candidates:
        for high in candidates:
            if low > high:
                continue
            pred = [_predict(s, low, high) for s in scores]
            # Prefer fewer unnecessary reviews only after equal macro-F1.
            review_rate = sum(x == "review" for x in pred) / len(pred)
            key = (_macro_f1(truth, pred), -review_rate, -low, high)
            if best is None or key > best[0]:
                best = (key, low, high, pred)
    _, low, high, pred = best
    return {
        "fail_below": round(low, 6), "pass_at_or_above": round(high, 6),
        "validation_metrics": agreement(list(zip(truth, pred))),
        "validation_n": len(rows), "objective": "macro_f1",
        "selection_note": "Thresholds selected using validation rows only; freeze before holdout evaluation.",
    }


def _dimension_report(rows: list[dict]) -> dict:
    counts: dict[str, dict[str, int]] = {}
    for row in rows:
        for name, values in (row.get("dimensions") or {}).items():
            if not isinstance(values, dict):
                continue
            item = counts.setdefault(name, {"n": 0, "human_disagreements": 0,
                                            "judge_vs_adjudicated_disagreements": 0})
            a, b = values.get("reviewer_a"), values.get("reviewer_b")
            if a is not None and b is not None:
                item["n"] += 1
                item["human_disagreements"] += _label(a, f"{name}.reviewer_a") != _label(b, f"{name}.reviewer_b")
            judge, ref = values.get("judge"), values.get("adjudicated")
            if judge is not None and ref is not None:
                item["judge_vs_adjudicated_disagreements"] += _label(judge, f"{name}.judge") != _label(ref, f"{name}.adjudicated")
    for item in counts.values():
        item["human_disagreement_rate"] = round(item["human_disagreements"] / item["n"], 4) if item["n"] else None
        item["judge_vs_adjudicated_disagreement_rate"] = round(
            item["judge_vs_adjudicated_disagreements"] / item["n"], 4) if item["n"] else None
    return dict(sorted(counts.items(), key=lambda kv: (
        -(kv[1]["human_disagreement_rate"] or 0), kv[0]
    )))


def analyze_reliability(records: Iterable[dict]) -> dict:
    rows = list(records)
    if not rows:
        raise ValueError("No calibration records supplied")
    ids = [str(r.get("trace_id", "")).strip() for r in rows]
    if any(not x for x in ids) or len(set(ids)) != len(ids):
        raise ValueError("Every record needs a unique, non-empty trace_id")
    if any(r.get("split") not in SPLITS for r in rows):
        raise ValueError("Every record split must be validation or holdout")
    validation = [r for r in rows if r["split"] == "validation"]
    holdout = [r for r in rows if r["split"] == "holdout"]
    if not validation or not holdout:
        raise ValueError("Both validation and untouched holdout rows are required")

    def labels(row: dict) -> tuple[str, str, str, str]:
        required = ("reviewer_a_decision", "reviewer_b_decision",
                    "adjudicated_decision", "judge_decision", "judge_score")
        missing = [k for k in required if k not in row]
        if missing:
            raise ValueError(f"Trace {row['trace_id']} missing fields: {', '.join(missing)}")
        score = float(row["judge_score"])
        if not 0 <= score <= 1:
            raise ValueError(f"Trace {row['trace_id']} judge_score must be in [0, 1]")
        return (_label(row["reviewer_a_decision"], "reviewer_a_decision"),
                _label(row["reviewer_b_decision"], "reviewer_b_decision"),
                _label(row["adjudicated_decision"], "adjudicated_decision"),
                _label(row["judge_decision"], "judge_decision"))

    parsed = {str(r["trace_id"]): labels(r) for r in rows}
    thresholds = calibrate_thresholds(validation)
    low, high = thresholds["fail_below"], thresholds["pass_at_or_above"]

    def evaluate(subset: list[dict]) -> dict:
        ref = [parsed[str(r["trace_id"])][2] for r in subset]
        raw_judge = [parsed[str(r["trace_id"])][3] for r in subset]
        calibrated = [_predict(float(r["judge_score"]), low, high) for r in subset]
        return {
            "n": len(subset),
            "raw_judge_vs_adjudicated": agreement(list(zip(ref, raw_judge))),
            "calibrated_score_vs_adjudicated": agreement(list(zip(ref, calibrated))),
            "review_rate": round(sum(x == "review" for x in calibrated) / len(calibrated), 4),
        }

    return {
        "protocol": "fixed_validation_holdout_v1",
        "split_sizes": {"validation": len(validation), "holdout": len(holdout)},
        "human_human_agreement": {
            "validation": agreement([(parsed[str(r["trace_id"])][0], parsed[str(r["trace_id"])][1]) for r in validation]),
            "holdout": agreement([(parsed[str(r["trace_id"])][0], parsed[str(r["trace_id"])][1]) for r in holdout]),
        },
        "judge_vs_adjudicated": {
            "validation": agreement([(parsed[str(r["trace_id"])][2], parsed[str(r["trace_id"])][3]) for r in validation]),
            "holdout": agreement([(parsed[str(r["trace_id"])][2], parsed[str(r["trace_id"])][3]) for r in holdout]),
        },
        "dimension_disagreement": {
            "validation": _dimension_report(validation), "holdout": _dimension_report(holdout),
        },
        "threshold_calibration": thresholds,
        "frozen_threshold_holdout_evaluation": evaluate(holdout),
        "limitations": [
            "Adjudicated labels are the operational reference, not infallible truth.",
            "Do not tune thresholds after inspecting holdout results; collect a new holdout for any recalibration.",
            "Kappa is prevalence-sensitive; inspect confusion matrices and class support.",
            "Dimension rates are descriptive and depend on consistent rubric definitions.",
            "A numeric judge_score must be a documented, consistently scaled judge output, not the lexical overlap heuristic.",
        ],
    }


def load_jsonl(path: str | Path) -> list[dict]:
    rows = []
    with Path(path).open(encoding="utf-8") as handle:
        for number, line in enumerate(handle, 1):
            if line.strip():
                value = json.loads(line)
                if not isinstance(value, dict):
                    raise ValueError(f"Line {number} must be a JSON object")
                rows.append(value)
    return rows


def main() -> None:
    parser = argparse.ArgumentParser(description="Human and judge reliability plus score calibration")
    parser.add_argument("input", help="JSONL calibration dataset")
    parser.add_argument("--output", default="calibration_reliability_report.json")
    args = parser.parse_args()
    report = analyze_reliability(load_jsonl(args.input))
    Path(args.output).write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
